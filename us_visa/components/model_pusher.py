
# ==============================================================================
# us_visa/components/model_pusher.py
#
# Model Pusher Component
# ------------------------------------------------------------------------------
# Responsibility:
#     Upload the trained model to the AWS S3 model registry after the model
#     has successfully passed the Model Evaluation stage.
# ==============================================================================

import sys

from us_visa.exception import USvisaException
from us_visa.logger import logging

from us_visa.entity.artifact_entity import (
    ModelEvaluationArtifact,
    ModelPusherArtifact
)

from us_visa.entity.config_entity import ModelPusherConfig

from us_visa.entity.s3_estimator import USvisaEstimator


class ModelPusher:
    """
    Model Pusher component responsible for uploading the accepted trained
    model to the configured AWS S3 model registry.
    """

    def __init__(
        self,
        model_evaluation_artifact: ModelEvaluationArtifact,
        model_pusher_config: ModelPusherConfig
    ):
        """
        Initialize the Model Pusher component.

        Args:
            model_evaluation_artifact:
                Artifact generated by the Model Evaluation component.
                Contains the path of the trained model that was evaluated.

            model_pusher_config:
                Configuration containing the AWS S3 bucket name and
                model storage path.
        """

        try:
            # Store the Model Evaluation artifact for accessing
            # the trained model path.
            self.model_evaluation_artifact = model_evaluation_artifact

            # Store the Model Pusher configuration.
            self.model_pusher_config = model_pusher_config

            # Initialize the S3 model estimator.
            #
            # USvisaEstimator provides the interface for saving,
            # loading, and predicting with models stored in S3.
            self.usvisa_estimator = USvisaEstimator(
                bucket_name=model_pusher_config.bucket_name,
                model_path=model_pusher_config.s3_model_key_path
            )

        except Exception as e:
            raise USvisaException(e, sys) from e


    # ==========================================================================
    # INITIATE MODEL PUSHER
    # ==========================================================================

    def initiate_model_pusher(self) -> ModelPusherArtifact:
        """
        Upload the evaluated trained model to AWS S3.

        The trained model path is obtained from the Model Evaluation artifact.
        The model is then uploaded to the configured S3 bucket and model path.

        Returns:
            ModelPusherArtifact:
                Contains the S3 bucket name and S3 model path.

        Raises:
            USvisaException:
                If any error occurs during the model upload process.
        """

        logging.info(
            "Entered initiate_model_pusher method of ModelPusher class"
        )

        try:

            # ------------------------------------------------------------------
            # Step 1: Get the local trained model path.
            #
            # This path was generated by the Model Trainer and passed through
            # the Model Evaluation artifact.
            # ------------------------------------------------------------------

            trained_model_path = (
                self.model_evaluation_artifact.trained_model_path
            )

            logging.info(
                f"Trained model path: {trained_model_path}"
            )


            # ------------------------------------------------------------------
            # Step 2: Upload the trained model to AWS S3.
            #
            # USvisaEstimator handles the actual interaction with S3.
            # ------------------------------------------------------------------

            logging.info(
                "Uploading trained model to AWS S3..."
            )

            self.usvisa_estimator.save_model(
                from_file=trained_model_path
            )

            logging.info(
                "Successfully uploaded trained model to AWS S3."
            )


            # ------------------------------------------------------------------
            # Step 3: Create Model Pusher Artifact.
            #
            # This artifact records where the model has been stored in S3.
            # ------------------------------------------------------------------

            model_pusher_artifact = ModelPusherArtifact(
                bucket_name=self.model_pusher_config.bucket_name,
                s3_model_path=self.model_pusher_config.s3_model_key_path
            )


            # ------------------------------------------------------------------
            # Step 4: Log the generated artifact.
            # ------------------------------------------------------------------

            logging.info(
                f"Model Pusher Artifact: {model_pusher_artifact}"
            )

            logging.info(
                "Exited initiate_model_pusher method of ModelPusher class"
            )


            # ------------------------------------------------------------------
            # Step 5: Return the Model Pusher artifact.
            # ------------------------------------------------------------------

            return model_pusher_artifact


        except Exception as e:

            # Convert the original exception into the project's custom
            # USvisaException while preserving the original traceback.
            raise USvisaException(e, sys) from e
