# ==============================================================================
# us_visa/components/model_trainer.py
#
# Model Trainer Component
#
# Responsibilities:
#     1. Load transformed training and testing data.
#     2. Use neuro_mf to train and compare candidate ML models.
#     3. Select the best-performing model.
#     4. Evaluate the selected model on the test dataset.
#     5. Combine the trained model with the preprocessing object.
#     6. Save the final model object.
#     7. Return ModelTrainerArtifact.
#
# Pipeline Flow:
#
#     DataTransformationArtifact
#               ↓
#        ModelTrainer
#               ↓
#       ModelFactory / GridSearchCV
#               ↓
#          Best Model
#               ↓
#       Model Evaluation
#               ↓
#        USvisaModel
#               ↓
#           model.pkl
#               ↓
#       ModelTrainerArtifact
# ==============================================================================


import sys
from typing import Tuple

import numpy as np

from sklearn.metrics import (
    accuracy_score,
    f1_score,
    precision_score,
    recall_score
)

from neuro_mf import ModelFactory

from us_visa.exception import USvisaException
from us_visa.logger import logging

from us_visa.utils.main_utils import (
    load_numpy_array_data,
    load_object,
    save_object
)

from us_visa.entity.config_entity import ModelTrainerConfig

from us_visa.entity.artifact_entity import (
    DataTransformationArtifact,
    ModelTrainerArtifact,
    ClassificationMetricArtifact
)

from us_visa.entity.estimator import USvisaModel


# ==============================================================================
# MODEL TRAINER CLASS
# ==============================================================================

class ModelTrainer:
    """
    Model Trainer component responsible for training, evaluating,
    and saving the best machine learning model.

    The component receives the transformed data generated by the
    Data Transformation component and uses neuro_mf to identify
    the best-performing model.

    Attributes:
        data_transformation_artifact:
            Artifact containing paths to transformed train/test
            datasets and the preprocessing object.

        model_trainer_config:
            Configuration containing model path, model configuration
            file path, and expected model performance.
    """

    # ==========================================================================
    # INITIALIZATION
    # ==========================================================================

    def __init__(
        self,
        data_transformation_artifact: DataTransformationArtifact,
        model_trainer_config: ModelTrainerConfig
    ):
        """
        Initialize the Model Trainer component.

        Args:
            data_transformation_artifact:
                Output artifact generated by Data Transformation.

            model_trainer_config:
                Configuration required by Model Trainer.
        """

        # Store the Data Transformation artifact.
        self.data_transformation_artifact = data_transformation_artifact

        # Store Model Trainer configuration.
        self.model_trainer_config = model_trainer_config


    # ==========================================================================
    # GET BEST MODEL AND EVALUATION METRICS
    # ==========================================================================

    def get_model_object_and_report(
        self,
        train: np.ndarray,
        test: np.ndarray
    ) -> Tuple[object, ClassificationMetricArtifact]:
        """
        Train candidate models and return the best model along with
        its evaluation metrics.

        Args:
            train:
                Transformed training dataset where the last column
                contains the target variable.

            test:
                Transformed testing dataset where the last column
                contains the target variable.

        Returns:
            Tuple containing:
                - best_model_detail
                - ClassificationMetricArtifact
        """

        try:

            # ------------------------------------------------------------------
            # Step 1: Initialize ModelFactory
            # ------------------------------------------------------------------

            logging.info(
                "Initializing neuro_mf ModelFactory."
            )

            model_factory = ModelFactory(
                model_config_path=(
                    self.model_trainer_config.model_config_file_path
                )
            )


            # ------------------------------------------------------------------
            # Step 2: Separate Features and Target
            # ------------------------------------------------------------------

            # The last column contains the target variable.
            #
            # Example:
            #
            #     [feature_1, feature_2, ..., feature_n, target]
            #
            # Therefore:
            #
            #     :-1 → input features
            #     -1  → target
            x_train = train[:, :-1]
            y_train = train[:, -1]

            x_test = test[:, :-1]
            y_test = test[:, -1]

            logging.info(
                "Separated training and testing features and target."
            )


            # ------------------------------------------------------------------
            # Step 3: Train and Select the Best Model
            # ------------------------------------------------------------------

            # ModelFactory reads model.yaml and:
            #
            #     - Creates the configured models
            #     - Performs hyperparameter tuning
            #     - Compares candidate models
            #     - Selects the best model
            #
            # base_accuracy acts as the minimum acceptable score.
            best_model_detail = model_factory.get_best_model(
                X=x_train,
                y=y_train,
                base_accuracy=(
                    self.model_trainer_config.expected_f1_score
                )
            )

            # Extract the selected best model.
            model_obj = best_model_detail.best_model

            logging.info(
                f"Best model selected: {model_obj}"
            )

            logging.info(
                f"Best cross-validation score: "
                f"{best_model_detail.best_score}"
            )


            # ------------------------------------------------------------------
            # Step 4: Generate Test Predictions
            # ------------------------------------------------------------------

            # Use the selected trained model to predict the unseen
            # testing dataset.
            y_pred = model_obj.predict(x_test)

            logging.info(
                "Generated predictions for the test dataset."
            )


            # ------------------------------------------------------------------
            # Step 5: Calculate Classification Metrics
            # ------------------------------------------------------------------

            accuracy = accuracy_score(
                y_test,
                y_pred
            )

            f1 = f1_score(
                y_test,
                y_pred
            )

            precision = precision_score(
                y_test,
                y_pred
            )

            recall = recall_score(
                y_test,
                y_pred
            )


            # Log the evaluation results.
            logging.info(
                f"Model Test Accuracy: {accuracy:.4f}"
            )

            logging.info(
                f"Model Test F1 Score: {f1:.4f}"
            )

            logging.info(
                f"Model Test Precision: {precision:.4f}"
            )

            logging.info(
                f"Model Test Recall: {recall:.4f}"
            )


            # ------------------------------------------------------------------
            # Step 6: Create Classification Metric Artifact
            # ------------------------------------------------------------------

            # Store the important classification metrics so that
            # downstream components can use them.
            metric_artifact = ClassificationMetricArtifact(
                f1_score=f1,
                precision_score=precision,
                recall_score=recall
            )


            # ------------------------------------------------------------------
            # Step 7: Return Best Model Details and Metrics
            # ------------------------------------------------------------------

            return (
                best_model_detail,
                metric_artifact
            )


        except Exception as e:

            # Convert the original exception into the project's
            # custom exception while preserving the traceback.
            raise USvisaException(e, sys) from e


    # ==========================================================================
    # INITIATE MODEL TRAINER
    # ==========================================================================

    def initiate_model_trainer(
        self
    ) -> ModelTrainerArtifact:
        """
        Initiate the complete Model Trainer process.

        Process:
            1. Load transformed train/test data.
            2. Train candidate models.
            3. Select the best model.
            4. Evaluate the best model.
            5. Validate the model performance.
            6. Load the preprocessing object.
            7. Combine preprocessing + trained model.
            8. Save the final model.
            9. Return ModelTrainerArtifact.

        Returns:
            ModelTrainerArtifact:
                Contains the path to the saved trained model
                and its evaluation metrics.
        """

        logging.info(
            "Entered initiate_model_trainer method of ModelTrainer."
        )

        try:

            # ------------------------------------------------------------------
            # Step 1: Load Transformed Training Data
            # ------------------------------------------------------------------

            train_arr = load_numpy_array_data(
                file_path=(
                    self.data_transformation_artifact
                    .transformed_train_file_path
                )
            )

            logging.info(
                "Loaded transformed training dataset."
            )


            # ------------------------------------------------------------------
            # Step 2: Load Transformed Testing Data
            # ------------------------------------------------------------------

            test_arr = load_numpy_array_data(
                file_path=(
                    self.data_transformation_artifact
                    .transformed_test_file_path
                )
            )

            logging.info(
                "Loaded transformed testing dataset."
            )


            # ------------------------------------------------------------------
            # Step 3: Train Models and Generate Metrics
            # ------------------------------------------------------------------

            best_model_detail, metric_artifact = (
                self.get_model_object_and_report(
                    train=train_arr,
                    test=test_arr
                )
            )

            logging.info(
                "Successfully trained and evaluated candidate models."
            )


            # ------------------------------------------------------------------
            # Step 4: Validate Best Model Performance
            # ------------------------------------------------------------------

            if (
                best_model_detail.best_score
                < self.model_trainer_config.expected_f1_score
            ):

                logging.info(
                    "Best model does not meet the minimum expected F1 score."
                )

                raise Exception(
                    "No suitable model found with the required "
                    "minimum F1 score."
                )


            logging.info(
                "Best model passed the minimum performance threshold."
            )


            # ------------------------------------------------------------------
            # Step 5: Load Fitted Preprocessing Object
            # ------------------------------------------------------------------

            # Load the preprocessing object that was fitted during
            # Data Transformation.
            preprocessing_obj = load_object(
                file_path=(
                    self.data_transformation_artifact
                    .transformed_object_file_path
                )
            )

            logging.info(
                "Loaded fitted preprocessing object."
            )


            # ------------------------------------------------------------------
            # Step 6: Combine Preprocessor and Trained Model
            # ------------------------------------------------------------------

            # Create a custom USvisaModel object containing:
            #
            #     preprocessing object
            #             +
            #     trained ML model
            #
            # This guarantees that the same preprocessing steps are
            # applied when making predictions on new raw data.
            usvisa_model = USvisaModel(
                preprocessing_object=preprocessing_obj,
                trained_model_object=best_model_detail.best_model
            )

            logging.info(
                "Created USvisaModel with preprocessing and trained model."
            )


            # ------------------------------------------------------------------
            # Step 7: Save Final Model
            # ------------------------------------------------------------------

            # Save the complete model object to model.pkl.
            save_object(
                self.model_trainer_config.trained_model_file_path,
                usvisa_model
            )

            logging.info(
                f"Saved trained model at: "
                f"{self.model_trainer_config.trained_model_file_path}"
            )


            # ------------------------------------------------------------------
            # Step 8: Create Model Trainer Artifact
            # ------------------------------------------------------------------

            model_trainer_artifact = ModelTrainerArtifact(
                trained_model_file_path=(
                    self.model_trainer_config
                    .trained_model_file_path
                ),
                metric_artifact=metric_artifact
            )

            logging.info(
                f"Model Trainer Artifact: {model_trainer_artifact}"
            )


            # ------------------------------------------------------------------
            # Step 9: Return Model Trainer Artifact
            # ------------------------------------------------------------------

            logging.info(
                "Exited initiate_model_trainer method successfully."
            )

            return model_trainer_artifact


        except Exception as e:

            # Convert the original exception into the project's
            # custom exception while preserving the traceback.
            raise USvisaException(e, sys) from e