# OUTPUT dataclasses returned by each pipeline component after execution
# ==============================================================================
from dataclasses import dataclass


# ------------------------------------------------------------------------------
# 1. DATA INGESTION ARTIFACT
# Returned by: DataIngestion.initiate_data_ingestion()
# Consumed by: DataValidation component
# ------------------------------------------------------------------------------
@dataclass
class DataIngestionArtifact:
    """Stores outputs generated by the data ingestion component."""
    trained_file_path : str
    test_file_path : str


# ------------------------------------------------------------------------------
# 2. DATA VALIDATION ARTIFACT
# Returned by: DataValidation.initiate_data_validation()
# Consumed by: DataTransformation component
# ------------------------------------------------------------------------------
@dataclass
class DataValidationArtifact:
    validation_status: bool
    message: str
    drift_report_file_path: str

# ------------------------------------------------------------------------------
# 3. DATA TRANSFORMATION ARTIFACT
# Output returned by DataTransformation component after execution
# Consumed by: ModelTrainer component 
# ------------------------------------------------------------------------------
@dataclass
class DataTransformationArtifact:
    """
    Proof that data was successfully transformed and saved.

    Attributes:
        transformed_train_file_path: Path to the processed train.npy
        transformed_test_file_path: Path to the processed test.npy 
        transformed_object_file_path: Path to the fitted preprocessor.pkl
    """
    transformed_object_file_path: set
    transformed_train_file_path: str
    transformed_test_file_path: str

# ==============================================================================
# 4. DATA TRANSFORMATION ARTIFACT
# ==============================================================================
@dataclass
class DataTransformationArtifact:
    """
    Stores the output generated by the Data Transformation component.

    This artifact is passed from Data Transformation to the
    Model Trainer component.

    Attributes:
        transformed_object_file_path:
            Path where the fitted preprocessing object is stored.

        transformed_train_file_path:
            Path to the transformed training dataset.

        transformed_test_file_path:
            Path to the transformed testing dataset.
    """

    # Path to the saved preprocessing object.
    # Example:
    # artifact/data_transformation/transformed_object/preprocessing.pkl
    transformed_object_file_path: str

    # Path to the transformed training dataset.
    transformed_train_file_path: str

    # Path to the transformed testing dataset.
    transformed_test_file_path: str


# ==============================================================================
# 5. MODEL TRAINER ARTIFACT
# ==============================================================================


# ==============================================================================
# CLASSIFICATION METRIC ARTIFACT
# ==============================================================================

@dataclass
class ClassificationMetricArtifact:
    """
    Stores classification evaluation metrics generated during
    model evaluation.

    Attributes:
        f1_score:
            Harmonic mean of precision and recall.

        precision_score:
            Percentage of predicted positive cases that are actually
            positive.

        recall_score:
            Percentage of actual positive cases correctly identified
            by the model.
    """

    # F1-score: Balance between precision and recall.
    f1_score: float

    # Precision: Correctness of positive predictions.
    precision_score: float

    # Recall: Ability to identify actual positive cases.
    recall_score: float


# ==============================================================================
# MODEL TRAINER ARTIFACT
# ==============================================================================

@dataclass
class ModelTrainerArtifact:
    """
    Stores the output generated by the Model Trainer component.

    This artifact is passed from Model Trainer to the next stage,
    such as Model Evaluation or Model Pusher.

    Attributes:
        trained_model_file_path:
            Path to the saved trained model.

        metric_artifact:
            Classification metrics generated for the trained model.
    """

    # Path to the saved final trained model.
    trained_model_file_path: str

    # Classification metrics of the trained model.
    metric_artifact: ClassificationMetricArtifact




# ==============================================================================
# 6. MODEL EVALUATION ARTIFACT
# ==============================================================================

@dataclass
class ModelEvaluationArtifact:
    """
    Stores the output of the Model Evaluation component.

    Attributes:
        is_model_accepted:
            Indicates whether the newly trained model is accepted for
            deployment based on the model evaluation criteria.

        changed_accuracy:
            Difference in model performance between the newly trained model
            and the existing registered model.

        s3_model_path:
            S3 path/key of the existing model stored in AWS S3.

        trained_model_path:
            Local path of the newly trained model generated by the
            Model Trainer component.
    """

    # --------------------------------------------------------------------------
    # Model acceptance status
    # --------------------------------------------------------------------------
    # True  → Newly trained model is accepted.
    # False → Existing model should be retained.
    is_model_accepted: bool


    # --------------------------------------------------------------------------
    # Model performance change
    # --------------------------------------------------------------------------
    # Represents the difference between the newly trained model's score
    # and the existing model's score.
    changed_accuracy: float


    # --------------------------------------------------------------------------
    # Existing model location in AWS S3
    # --------------------------------------------------------------------------
    # Stores the S3 location/key of the currently registered model.
    s3_model_path: str


    # --------------------------------------------------------------------------
    # Newly trained model location
    # --------------------------------------------------------------------------
    # Stores the local path of the model produced by Model Trainer.
    trained_model_path: str