# Custom estimator wrapper for the US Visa Prediction project.
#
# Purpose:
#     This class combines:
#         1. Preprocessing object
#         2. Trained ML model
#
#     During prediction, raw input data is first passed through the same
#     preprocessing pipeline used during training, and then the transformed
#     data is passed to the trained model.
#
# Prediction Flow:
#
#     Raw Input
#         ↓
#     Preprocessing Object
#         ↓
#     Transformed Features
#         ↓
#     Trained Model
#         ↓
#     Prediction
# ==============================================================================


import sys

import numpy as np
from pandas import DataFrame
from sklearn.pipeline import Pipeline

from us_visa.exception import USvisaException
from us_visa.logger import logging


class TargetValueMapping:
    """Defines the mapping for the US Visa target variable."""

    def __init__(self):
        # Define target labels used during model training
        self.mapping = {
            "Certified": 0,
            "Denied": 1
        }

    def as_dict(self) -> dict:
        """Return the forward target mapping."""

        return self.mapping

    def reverse_mapping(self) -> dict:
        """Return numeric label to original target mapping."""

        return {
            value: key
            for key, value in self.mapping.items()
        }

# ==============================================================================
# US VISA MODEL
# ==============================================================================

class USvisaModel:
    """
    Wrapper class that combines the preprocessing object and trained model.

    This ensures that the same preprocessing steps used during training
    are applied to new/raw input data before making predictions.

    Attributes:
        preprocessing_object:
            Fitted preprocessing pipeline used to transform input features.

        trained_model_object:
            Fitted machine learning model used to generate predictions.
    """

    def __init__(
        self,
        preprocessing_object: Pipeline,
        trained_model_object: object
    ):
        """
        Initialize the US Visa model wrapper.

        Args:
            preprocessing_object:
                Fitted preprocessing pipeline.

            trained_model_object:
                Fitted machine learning classification model.
        """

        # Store the fitted preprocessing pipeline.
        self.preprocessing_object = preprocessing_object

        # Store the trained machine learning model.
        self.trained_model_object = trained_model_object


    # ==========================================================================
    # PREDICTION METHOD
    # ==========================================================================

    def predict(self, dataframe: DataFrame) -> np.ndarray:
        """
        Generate predictions for raw input data.

        The raw input is first transformed using the fitted preprocessing
        object. The transformed features are then passed to the trained
        machine learning model.

        Args:
            dataframe:
                Raw input features in pandas DataFrame format.

        Returns:
            np.ndarray:
                Predictions generated by the trained model.
        """

        logging.info(
            "Entered predict method of USvisaModel."
        )

        try:

            # ------------------------------------------------------------------
            # Step 1: Transform Raw Input
            # ------------------------------------------------------------------

            # Apply the same preprocessing steps used during model training.
            # This may include:
            #     - One-Hot Encoding
            #     - Ordinal Encoding
            #     - Power Transformation
            #     - Standard Scaling
            transformed_feature = (
                self.preprocessing_object.transform(dataframe)
            )

            logging.info(
                "Successfully transformed input features."
            )


            # ------------------------------------------------------------------
            # Step 2: Generate Prediction
            # ------------------------------------------------------------------

            # Pass the transformed features to the trained ML model.
            prediction = (
                self.trained_model_object.predict(transformed_feature)
            )

            logging.info(
                "Successfully generated predictions using the trained model."
            )

            # Return the model predictions.
            return prediction


        except Exception as e:

            # Convert the original error into the project's
            # custom exception while preserving the traceback.
            raise USvisaException(e, sys) from e


    # ==========================================================================
    # STRING REPRESENTATION
    # ==========================================================================

    def __repr__(self) -> str:
        """
        Return a developer-friendly representation of the model.

        Example:
            RandomForestClassifier()
        """

        return (
            f"{type(self.trained_model_object).__name__}()"
        )


    def __str__(self) -> str:
        """
        Return a human-readable representation of the model.

        Example:
            RandomForestClassifier()
        """

        return (
            f"{type(self.trained_model_object).__name__}()"
        )